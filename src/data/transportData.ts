const DAY_INDEX: Record<string, number> = {
  یکشنبه: 0,
  دوشنبه: 1,
  سه‌شنبه: 2,
  چهارشنبه: 3,
  پنجشنبه: 4,
  جمعه: 5,
  شنبه: 6,
};

export interface NextDeparture {
  dayLabel: string;
  hoursFromNow: number;
  dateLabel: string;
}

/** نخستین حرکت بعدی یک برنامه از میان روزهای هفته */
export function nextDeparture(schedule: TransportSchedule, from: Date = new Date()): NextDeparture {
  const daily = schedule.departDays.includes('روزانه');
  let bestDiff = 99;

  schedule.departDays.forEach((d) => {
    if (d === 'روزانه') return;
    const idx = DAY_INDEX[d];
    if (idx === undefined) return;
    const diff = (idx - from.getDay() + 7) % 7;
    if (diff < bestDiff) bestDiff = diff;
  });

  const offset = daily ? 0 : bestDiff === 99 ? 1 : bestDiff;
  const date = new Date(from.getTime() + offset * 86400000);
  const dateLabel = date.toLocaleDateString('fa-IR', { month: 'long', day: 'numeric', weekday: 'long' });

  return {
    dayLabel: daily ? 'روزانه' : schedule.departDays.join(' / '),
    hoursFromNow: offset * 24,
    dateLabel,
  };
}

